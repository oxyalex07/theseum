// Home Crew uses real saved profiles in an isolated Electron store. No provider calls.
import { _electron, expect } from '@playwright/test';
import { mkdtemp, mkdir, writeFile, rm, realpath } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import assert from 'node:assert/strict';

const root=await realpath(await mkdtemp(join(tmpdir(),'theseus-home-crew-')));
const directory=join(root,'data'),project=join(root,'project'),binary=join(root,'codex');
await mkdir(project);await mkdir('artifacts/verification',{recursive:true});
await writeFile(binary,'#!/bin/sh\ncase "$*" in\n--version) echo "fixture codex";;\nlogin*) exit 0;;\n*app-server*) exit 1;;\n*) echo "[]";;\nesac\n',{mode:0o700});
const env={...process.env,THESEUS_USER_DATA_DIR:directory,THESEUS_CODEX_PATH:binary};
delete env.ELECTRON_RUN_AS_NODE;delete env.THESEUS_DEV_URL;delete env.THESEUS_SAMPLE_PREVIEW;
let desktop;const errors=[];
const draft=name=>({name,description:`${name} saved description`,icon:'shield',color:'green',runtime:'codex',model:null,reasoningEffort:null,instructions:'Fixture instructions',memory:'none',sandbox:'workspace-write',timeoutSeconds:60,folderChoice:null});
try{
  desktop=await _electron.launch({args:['.'],env});
  const page=await desktop.firstWindow();page.on('pageerror',error=>errors.push(error.message));
  await page.getByRole('textbox',{name:'Start a task',exact:true}).waitFor();
  await page.getByRole('tab',{name:'Crew',exact:true}).click();
  const panel=page.getByRole('tabpanel',{name:'Crew',exact:true});
  assert.equal((await page.evaluate(()=>window.theseus.listAgentProfiles())).profiles.length,0);
  console.log('Isolated zero-profile Home Crew rows:',await panel.locator('.am').allTextContents());
  await expect(panel.locator('.am')).toHaveCount(0);
  await expect(panel.getByText('No saved agents yet',{exact:true})).toBeVisible();
  await expect(panel.getByRole('button',{name:'Open brief',exact:true})).toHaveCount(0);
  await page.screenshot({path:'artifacts/verification/home-crew-empty.png'});
  await panel.getByRole('button',{name:'Create your first agent',exact:true}).click();
  await expect(page.getByRole('heading',{name:'Your agents',exact:true})).toBeVisible();
  const profiles=await page.evaluate(async drafts=>{
    const active=await window.theseus.saveAgentProfile(drafts[0]);
    const archived=await window.theseus.saveAgentProfile(drafts[1]);
    await window.theseus.changeAgentProfile({id:archived.id,expectedUpdatedAt:archived.updatedAt,action:'archive'});
    return {active,archived};
  },[draft('Saved builder'),draft('Archived reviewer')]);
  await page.reload();await page.getByRole('textbox',{name:'Start a task',exact:true}).waitFor();
  await page.getByRole('tab',{name:'Crew',exact:true}).click();
  await expect(panel.locator('.am')).toHaveCount(1);
  await expect(panel.getByText(profiles.active.description,{exact:true})).toBeVisible();
  await expect(panel.getByText(profiles.archived.name,{exact:true})).toHaveCount(0);
  await desktop.evaluate(({dialog},path)=>{dialog.showOpenDialog=async()=>({canceled:false,filePaths:[path]});},project);
  await page.getByRole('button',{name:'Choose project folder',exact:true}).click();
  const task=page.getByRole('textbox',{name:'Start a task',exact:true});await task.fill('Preserve this saved agent task draft');
  await page.getByLabel('Routing',{exact:true}).selectOption('feature');
  const row=panel.getByRole('button',{name:/Saved builder/});await row.click();
  await expect(page.getByLabel('Routing',{exact:true})).toHaveValue('single');
  await expect(page.getByLabel('Run agent',{exact:true})).toHaveValue(profiles.active.id);
  await expect(row).toHaveAttribute('aria-pressed','true');
  await expect(task).toHaveValue('Preserve this saved agent task draft');
  assert.equal((await page.evaluate(()=>window.theseus.getExecutionState())).workspace.path,project);
  assert.equal((await page.evaluate(()=>window.theseus.getExecutionState())).runs.length,0);
  await panel.getByRole('textbox',{name:'Search crew',exact:true}).fill('no such saved agent');
  await expect(panel.locator('.am')).toHaveCount(0);
  await panel.getByRole('textbox',{name:'Search crew',exact:true}).fill('');
  await panel.getByText('Configuration & activity',{exact:true}).click();
  await expect(panel.getByText('No runs with this saved agent yet.',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'Edit agent',exact:true}).click();
  await page.getByRole('dialog').getByLabel('Description · optional',{exact:true}).fill('Edited directly from Home');
  await page.getByRole('button',{name:'Save changes',exact:true}).click();
  await expect(panel.getByText('Edited directly from Home',{exact:true})).toBeVisible();
  profiles.active=(await page.evaluate(()=>window.theseus.listAgentProfiles())).profiles.find(profile=>profile.id===profiles.active.id);
  await expect(task).toHaveValue('Preserve this saved agent task draft');
  await panel.getByRole('button',{name:'Build → Review',exact:true}).click();
  await expect(page.getByLabel('Routing',{exact:true})).toHaveValue('feature');
  await row.click();
  await desktop.evaluate(({BrowserWindow})=>BrowserWindow.getAllWindows()[0].setSize(1100,700));
  assert.equal(await panel.evaluate(el=>el.scrollWidth<=el.clientWidth),true);
  await page.screenshot({path:'artifacts/verification/home-crew-saved.png'});
  await panel.getByRole('button',{name:'Show sample data',exact:true}).click();
  await expect(panel.locator('.am')).toHaveCount(12);
  await expect(panel.locator('.hsec-h').first()).toContainText('Sample crew');
  await expect(panel.getByText(profiles.active.name,{exact:true})).toHaveCount(0);
  await panel.locator('.am').first().click();
  await expect(page.getByRole('heading',{name:'Your agents',exact:true})).toBeVisible();
  await page.getByRole('navigation',{name:'Primary',exact:true}).getByRole('button',{name:'Home',exact:true}).click();
  await page.getByRole('tab',{name:'Crew',exact:true}).click();
  await expect(page.getByLabel('Run agent',{exact:true})).toHaveValue(profiles.active.id);
  await panel.getByRole('button',{name:'Show saved data',exact:true}).click();
  await expect(panel.locator('.am')).toHaveCount(1);
  assert.equal((await page.evaluate(()=>window.theseus.listAgentProfiles())).profiles.length,2);
  // A stale visible row must report backend rejection rather than navigate to a mock session.
  await page.evaluate(profile=>window.theseus.changeAgentProfile({id:profile.id,expectedUpdatedAt:profile.updatedAt,action:'delete'}),profiles.active);
  await row.click();
  await expect(page.getByRole('status').filter({hasText:/not found/})).toBeVisible();
  await expect(task).toHaveValue('Preserve this saved agent task draft');
  await page.reload();await task.waitFor();
  await page.getByRole('tab',{name:'Crew',exact:true}).click();
  await expect(panel.locator('.am')).toHaveCount(0);
  await expect(panel.getByText('No saved agents yet',{exact:true})).toBeVisible();
  await panel.getByRole('button',{name:'New agent',exact:true}).click();
  await page.getByRole('dialog').getByLabel('Name · required',{exact:true}).fill('Created on Home');
  await page.getByRole('dialog').getByRole('button',{name:'Create agent',exact:true}).click();
  await expect(panel.locator('.am')).toHaveCount(1);
  await expect(panel.getByRole('button',{name:/Created on Home/})).toBeVisible();
  assert.equal((await page.evaluate(()=>window.theseus.getExecutionState())).runs.length,0);
  assert.deepEqual(errors,[]);
  console.log('PASS isolated zero-profile state, manage navigation, active saved profiles, archived exclusion, saved selection/draft/project preservation, single routing, sample separation, stale selection error and no runs/provider calls');
}finally{await desktop?.close();await rm(root,{recursive:true,force:true});}
